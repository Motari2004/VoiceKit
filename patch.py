"""
Hide the hamburger button completely (display: none) when the sidebar is open.
"""

import os
import shutil

BASE = os.path.dirname(os.path.abspath(__file__))
HTML = os.path.join(BASE, "templates", "index.html")


def backup(path):
    if os.path.exists(path):
        shutil.copy(path, path + ".bak")
        print(f"  backed up -> {os.path.relpath(path, BASE)}.bak")


NEW_CSS = '''
  /* ---------- HAMBURGER HIDES COMPLETELY WHEN SIDEBAR IS OPEN ---------- */
  @media (max-width: 900px) {
    .menu-toggle.hidden {
      display: none;
    }
  }
'''


def patch():
    print("=" * 60)
    print(" VoiceKit — Hide Hamburger When Open")
    print("=" * 60)

    if not os.path.exists(HTML):
        print(f"ERROR: {HTML} not found")
        return

    backup(HTML)

    with open(HTML, "r", encoding="utf-8") as f:
        src = f.read()

    if 'HAMBURGER HIDES COMPLETELY' in src:
        print("  Already applied.")
        return

    src = src.replace('</style>', NEW_CSS + '\n</style>', 1)

    with open(HTML, "w", encoding="utf-8") as f:
        f.write(src)

    print("  [OK] Hamburger now hides with display: none")
    print()
    print(" Deploy:")
    print("   vercel --prod")
    print("   Or hard-refresh: Ctrl + Shift + R")
    print("=" * 60)


if __name__ == "__main__":
    patch()